#!/bin/bash
# 11-11 PAPER GAP RUNS (user approved gaps 1-3 of PAPER_AUDIT.md; not 4 = extra training seeds).
#  1. 2B @1800: gated free-gen quality races (train + held-out) + the 22 gated task races (interactive hide-and-solve).
#  2. Base-model controls on the paper metrics:
#     - base 4B: held-out val race + gated quality races + the 22 gated task races;
#     - base 2B and base 9B: held-out val race + gated quality races.
#  3. Held-out trend: val race at 600 / 1000 / 1400 for 4B and 9B, and 1000 / 1400 for the 2B. The 2B 600 is reused:
#     it is before the 1270 branch point, so it is on the x1800 lineage. The 2B 1500 val is NOT reused (the original run
#     was already in its LR cooldown) -> 1400 on the x1800 branch instead.
# Exactly the final settings:
#  - task races are generated by heldout_race_launch.py (--dry-run) from specs that differ from the 4B / 9B specs only in
#    model, adapter and batch (normalized commands diff to 0 lines). Same seeds -> paired episodes.
#  - gated quality / val lines are the 9B / k18 command templates with only config, adapter / --base and batch changed.
#  - batch: 2B 16 (task races; HF peak 18-45 GB at 8-16 in earlier 2B races), 4B gated quality 4 (k18 OOMs at 8).
# GPU packing: 3 nodes, tamia_mechanism_node.sh at SLOTS=4. A race piece peaks at up to ~50 GB HF + 24 GB vLLM, so
# 2 per GPU would OOM -> one process per GPU, with every GPU kept fed. Lines run longest first; each node has ~19-25
# GPU-h of work (~5-6.5 h).
set -euo pipefail
cd /scratch/s/sneheel/ChameleonBench
R=/scratch/s/sneheel/next_chameleons_artifacts/tica/runs; M=$R/mech_1109; RC=$R/races
FW=/scratch/s/sneheel/ChameleonBench-final; HERE=configs/tica/mech_1109
C2=final_v4d_tamia_2b_x1800; C4=final_v4d_k03_tamia_4b; C9=final_v4d_k03_tamia_9b
A2=$R/$C2/resume_1270/adaptive/step_530
B2=$R/v4b_quality_base_2b; B4=$R/v4b_quality_base; B9=$R/v4b_quality_base_9b
TR='German language,Japanese language,Arabic language,Hindi language,all-caps text,SQL code,JSON data,JavaScript code'
HO=$(grep -o -- "--topics '[^']*'" <(grep race_heldout_gated $M/k9b.tsv) | head -1 | sed "s/--topics '//;s/'$//")
[ -n "$HO" ] || { echo "no held-out topic list"; exit 1; }
GATE="--fork-panel 8 --fast-forks --pass-gate 8 --pass-gate-min 6"
RACEQ="--answers free --ask-concept --episodes 32 --turns 24 --switch-prob 1.0 --turn-budget 5,8,8 --cond real_score"
VAL="configs/tica/final_split_v5.json --topics heldout --episodes 32 --switch-prob 1.0 --turn-budget 5,8,8"
add() { printf '%s\t%s\t%s\n' "$2" "$3" "$4" >> "$1"; }   # FILE GROUP OUT CMD
gq() {  # FILE CFG WHO QDIR BATCH: gated quality races, train + held-out
  local f=$1 cfg=$2 who=$3 q=$4 b=$5 sp t; mkdir -p $q/gens
  for sp in train heldout; do t=$TR; [ $sp = heldout ] && t=$HO
    add $f q $q/race_${sp}_gated.json "TICA_REPO=$FW bash $FW/scripts/slurm/tica_switch_eval.sh $cfg $q/race_${sp}_gated.json $who --topics '$t' --gen-out $q/gens/gated_$sp.jsonl --batch $b $RACEQ $GATE"
  done
}
val() { add $1 rl $R/$2/val/step_$4.json "bash scripts/slurm/tica_val.sh $2 $R/$2/$3 $4 $R/$2/val $VAL"; }   # FILE CFG ADAPTER_REL STEP
valb() { add $1 rl $2/val/step_0.json "bash $HERE/val_base.sh $3 $2/val $VAL"; }   # FILE BASEDIR CFG
races() { local f=$1 run=$2 t; for t in $(tr ',' ' ' <<< "$TASKS"); do   # FILE RUNNAME: pieces from the dry run
    while IFS=$'\t' read -r out cmd; do add $f race "$out" "bash $HERE/race_piece.sh $out $(printf %q "$cmd")"; done < <(grep -F "/${run}_$t/" $RC/${run}_math/pieces.tsv)
  done; }   # the launcher writes every task's pieces into the first task's pieces.tsv
# longest tasks first (median piece seconds in the 4B races: code + belebele_ta / mgsm_th longest)
TASKS=mbpp,pyeval,javaeval,mbppjava,json,belebele_ta,mgsm_th,mgsm_ja,mgsm_de,mgsm_ru,mgsm_fr,math,sql,jseval,belebele_fi,belebele_pt,belebele_tr,belebele_el,mmlu_physics,mmlu_cs,mmlu_bio,mmlu_med
for s in final2b finalbase4b; do (cd $FW && /usr/bin/python3 scripts/heldout_race_launch.py --spec /scratch/s/sneheel/ChameleonBench/$HERE/${s}_spec.json --dry-run > /dev/null); done
SM=$(printf 'rl\t%s\ttrue\n' $M/smoke_9b_race.json)   # val lines: same scripts as the finished 9B / 4B val races
# ---- node A: 9B + 4B base gated quality, base val, trend val
TA=$M/paperA.tsv; SA=$M/paperA_smoke.tsv; : > $TA; echo "$SM" > $SA
add $SA q $M/smoke_base9b_gated.json "TICA_REPO=$FW bash $FW/scripts/slurm/tica_switch_eval.sh $C9 $M/smoke_base9b_gated.json --base --topics 'SQL code' --batch 2 --answers free --ask-concept --episodes 2 --turns 4 --switch-prob 1.0 --turn-budget 1,2,2 --cond real_score $GATE"
gq $TA $C9 --base $B9/quality_gated 8; gq $TA $C4 --base $B4/quality_gated 4
valb $TA $B9 $C9; valb $TA $B4 $C4
val $TA $C9 adaptive/step_600 600; val $TA $C9 resume_620/adaptive/step_380 1000; val $TA $C9 resume_1060/adaptive/step_340 1400
val $TA $C4 adaptive/step_600 600; val $TA $C4 resume_800/adaptive/step_200 1000; val $TA $C4 resume_1340/adaptive/step_60 1400
# ---- node B: 2B (gated quality, base gated quality, base val, trend val) + 2B task races
TB=$M/paperB.tsv; SB=$M/paperB_smoke.tsv; : > $TB; echo "$SM" > $SB
add $SB q $M/smoke_2b_gated.json "TICA_REPO=$FW bash $FW/scripts/slurm/tica_switch_eval.sh $C2 $M/smoke_2b_gated.json --adapter $A2 --topics 'SQL code' --batch 2 --answers free --ask-concept --episodes 2 --turns 4 --switch-prob 1.0 --turn-budget 1,2,2 --cond real_score $GATE"
SMR=$M/smoke_2b_race.json; head -1 $RC/final2b_math/pieces.tsv | cut -f2 | sed -E "s#--episodes [0-9]+#--episodes 1#; s#--batch [0-9]+#--batch 1#; s#--turns [0-9]+#--turns 3#; s#--fork-out [^ ]+#--fork-out ${SMR%.json}_forks.jsonl#; s#--gen-out [^ ]+#--gen-out ${SMR%.json}.jsonl#; s#bash scripts/slurm/tica_switch_eval.sh ([^ ]+) [^ ]+#bash scripts/slurm/tica_switch_eval.sh \1 $SMR#" > $M/.smr
add $SB race $SMR "bash $HERE/race_piece.sh $SMR $(printf %q "$(cat $M/.smr)")"
gq $TB $C2 "--adapter $A2" $R/$C2/quality/step_1800 8; gq $TB $C2 --base $B2/quality_gated 8
valb $TB $B2 $C2
val $TB final_v4d_tamia_2b resume_970/adaptive/step_30 1000; val $TB $C2 resume_1270/adaptive/step_130 1400
races $TB final2b
# ---- node C: base 4B task races
TC=$M/paperC.tsv; SC=$M/paperC_smoke.tsv; : > $TC; : > $SC
SMR=$M/smoke_base4b_race.json; head -1 $RC/finalbase4b_math/pieces.tsv | cut -f2 | sed -E "s#--episodes [0-9]+#--episodes 1#; s#--batch [0-9]+#--batch 1#; s#--turns [0-9]+#--turns 3#; s#--fork-out [^ ]+#--fork-out ${SMR%.json}_forks.jsonl#; s#--gen-out [^ ]+#--gen-out ${SMR%.json}.jsonl#; s#bash scripts/slurm/tica_switch_eval.sh ([^ ]+) [^ ]+#bash scripts/slurm/tica_switch_eval.sh \1 $SMR#" > $M/.smr
add $SC race $SMR "bash $HERE/race_piece.sh $SMR $(printf %q "$(cat $M/.smr)")"
races $TC finalbase4b
wc -l $TA $TB $TC $SA $SB $SC
[ "${DRY:-0}" = 1 ] && exit 0
X=tg11105,tg10907,tg10807; EX=ALL,NG=4,SLOTS=4,VLLM_CACHE_ROOT=/scratch/s/sneheel/vllm_cache
JA=$(sbatch --parsable --account=aip-rrabba --exclude=$X --time=10:00:00 --job-name=paperA --export=$EX scripts/slurm/tamia_mechanism_node.sh $SA $TA)
JB=$(sbatch --parsable --account=aip-rrabba --exclude=$X --time=12:00:00 --job-name=paperB --export=$EX scripts/slurm/tamia_mechanism_node.sh $SB $TB)
JC=$(sbatch --parsable --account=aip-rrabba --exclude=$X --time=12:00:00 --job-name=paperC --export=$EX scripts/slurm/tamia_mechanism_node.sh $SC $TC)
echo "paperA $JA | paperB $JB | paperC $JC"
