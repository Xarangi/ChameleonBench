"""MODEL-WRITTEN concept texts, step 3: rebuild the split-v5 data file with the base model's own
judged answers (REPLICATION 2026-10-21f; docs/tica/V4_MODEL_WRITTEN_DATA.md).

PROVENANCE: requests = published (the v5 elicit request file: the sources' own prompts, + a
language / tone / format line, or a 27B-written request for DBpedia topics); responses =
SELF-GENERATED by the base model (scripts/tica_mw_generate.py) and kept only if the 27B judge
(scripts/tica_free_judge.py --answers-prompt loose) says the concept is present / central AND the
answer is a reasonable answer, and the answer finished (no max-token cut).

  build         replace the fit / calib / episode texts of the regenerated concepts:
                - SPLITS BY REQUEST: every answer to a request lands in ONE split: the split of its
                  source text; a request whose source texts span several splits goes to the split
                  holding most of them (ties: fit, calib, episode order);
                - per source text, the kept answer closest in length to the source text (the
                  current data's lengths and memory); --fill tops each split back up to its old
                  count with other kept answers to requests of that split;
                - new ids = text_id(answer) (the episode code looks requests up by text_id);
                  duplicates of any text already in the file are dropped;
                - every other concept, the negatives and hard_neg are copied unchanged;
                - new request file = the old map + {new id: request};
                - report: per concept / split kept / dropped, judge pass rates, lengths.
  merge-labels  27B negative labels for the new file = labels of the NEW texts (label job with
                --skip-labelled) + the old labels of every text that kept its id.
Aggregates only; outputs go to scratch, never commit.

  python scripts/build_final_v5_mw.py build --data D.json --inputs I.json --gens G*.jsonl \
      --scores S*.jsonl --out D_mw.json --inputs-out I_mw.json --report R.json
  python scripts/build_final_v5_mw.py merge-labels --data D_mw.json --old L_old.json \
      --new L_new_s*.json --out L_mw.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
import statistics
from collections import Counter, defaultdict
from pathlib import Path

SPLITS = ("fit", "calib", "episode")


def text_id(text: str) -> str:  # = next_chameleons.tica.answer_format.text_id
    return "ax-" + hashlib.sha256(text.encode()).hexdigest()[:12]


def read_jsonl(paths) -> list[dict]:
    out = []
    for p in paths:
        out += [json.loads(x) for x in Path(p).read_text().splitlines() if x.strip()]
    return out


def request_splits(src_rows: list[dict]) -> dict[str, str]:
    """{request: split}: the split holding most of the request's source texts (ties: SPLITS
    order), so every answer to one request lands in one split."""

    cnt: dict[str, Counter] = defaultdict(Counter)
    for r in src_rows:
        cnt[r["user"]][r["src_split"]] += 1
    return {u: max(SPLITS, key=lambda s, c=c: (c[s], -SPLITS.index(s))) for u, c in cnt.items()}


def keep(g: dict, s: dict, thr_concept: float, thr_answers: float) -> bool:
    pc = s.get("p_concept")
    return (bool(g["finished"]) and bool(g["answer"].strip())
            and (pc is None or pc >= thr_concept) and s.get("p_answers", 0.0) >= thr_answers)


def build(data: dict, inputs: dict, gens: list[dict], scores: dict[str, dict], *,
          thr_concept: float = 0.5, thr_answers: float = 0.5, fill: bool = True,
          len_cap_q: float | None = 0.9,
          seed: int = 0, only: set[str] | None = None) -> tuple[dict, dict, dict]:
    """Returns (new data, new request entries {id: request}, report). Pure (tested on CPU)."""

    rng = random.Random(seed)
    by_c: dict[str, list[dict]] = defaultdict(list)
    for g in gens:
        if only is None or g["concept"] in only:
            by_c[g["concept"]].append(g)
    taken = {t["id"] for c in data["concepts"] for sp in SPLITS for t in c[sp]}
    taken |= {t["id"] for ts in data["negatives"].values() for t in ts}
    for c in data["concepts"]:
        for ts in (c.get("hard_neg") or {}).values():
            taken |= {text_id(x) if isinstance(x, str) else x["id"] for x in ts}
    new = json.loads(json.dumps(data))
    new_inputs: dict[str, str] = {}
    rep: dict = {}
    for c in new["concepts"]:
        name = c["concept"]
        rows = by_c.get(name)
        if not rows:
            continue
        old_n = {sp: len(c[sp]) for sp in SPLITS}
        old_len = {t["id"]: len(t["text"]) for sp in SPLITS for t in c[sp]}
        cap = length_cap(list(old_len.values()), len_cap_q)
        # one row per source text (its request + split) -> request -> split
        src = {g["src_id"]: g for g in rows}
        rsplit = request_splits(list(src.values()))
        moved = sum(rsplit[g["user"]] != g["src_split"] for g in src.values())
        judged = [g for g in rows if g["gid"] in scores and keep(g, scores[g["gid"]], thr_concept,
                                                                  thr_answers)]
        # LENGTH CAP (user 10-21): eligible only if <= the concept's published p90 length (chars)
        ok = [g for g in judged if cap is None or len(g["answer"]) <= cap]
        per_src: dict[str, list[dict]] = defaultdict(list)
        for g in ok:
            per_src[g["src_id"]].append(g)
        chosen: dict[str, list[dict]] = {sp: [] for sp in SPLITS}
        spare: dict[str, list[dict]] = {sp: [] for sp in SPLITS}
        dup = 0
        for sid in sorted(per_src):  # deterministic
            cands = sorted(per_src[sid], key=lambda g: (abs(len(g["answer"])
                                                            - old_len.get(sid, g["src_len"])),
                                                        g["sample"]))
            sp = rsplit[src[sid]["user"]]
            first = True
            for g in cands:
                tid = text_id(g["answer"])
                if tid in taken:
                    dup += 1
                    continue
                if first:
                    chosen[sp].append(g)
                    first = False
                else:
                    spare[sp].append(g)
                taken.add(tid)
        for sp in SPLITS:
            rng.shuffle(chosen[sp])
            rng.shuffle(spare[sp])
            pick = chosen[sp][: old_n[sp]]
            if fill and len(pick) < old_n[sp]:
                pick += spare[sp][: old_n[sp] - len(pick)]
            c[sp] = [{"id": text_id(g["answer"]), "text": g["answer"]} for g in pick]
            for g in pick:
                new_inputs[text_id(g["answer"])] = g["user"]
        scored = [scores[g["gid"]] for g in rows if g["gid"] in scores]
        n_new = {sp: len(c[sp]) for sp in SPLITS}
        lens = [len(t["text"]) for sp in SPLITS for t in c[sp]]
        rep[name] = {
            "split": c["split"], "n_gen": len(rows), "n_scored": len(scored),
            "finished": round(sum(g["finished"] for g in rows) / len(rows), 3),
            "concept_rate": _rate([s.get("p_concept") for s in scored], thr_concept),
            "answers_rate": _rate([s.get("p_answers") for s in scored], thr_answers),
            "kept_gen": len(ok), "keep_rate": round(len(ok) / len(rows), 3),
            "src_with_keep": f"{len(per_src)}/{len(src)}", "dup_dropped": dup,
            "requests_moved_split": moved, "old": old_n, "new": n_new,
            "new_total": sum(n_new.values()), "old_total": sum(old_n.values()),
            "median_chars_old": statistics.median(old_len.values()) if old_len else None,
            "median_chars_new": statistics.median(lens) if lens else None,
            "len_cap_chars": cap, "kept_judged": len(judged),
            "src_no_eligible": len(src) - len(per_src),
            "src_judged_but_over_cap": len({g["src_id"] for g in judged} - set(per_src)),
            "new_frac_of_old": round(sum(n_new.values()) / max(1, sum(old_n.values())), 3),
            "below_80pct": sum(n_new.values()) < 0.8 * sum(old_n.values())}
    src_meta = new.setdefault("source", {})
    src_meta["model_written"] = {
        "provenance": "requests: published (v5 elicit request file); responses: self-generated "
                      "by the base model (Qwen3.5-4B, scripts/tica_mw_generate.py), filtered by "
                      "the Qwen3.5-27B-FP8 judge (tica_free_judge.py --answers-prompt loose)",
        "concepts": sorted(rep), "thr_concept": thr_concept, "thr_answers": thr_answers,
        "require_finished": True, "fill": fill, "seed": seed,
        "len_cap": None if len_cap_q is None else f"p{round(100 * len_cap_q)} of the concept's "
                   "published text lengths (chars)",
        "builder": "scripts/build_final_v5_mw.py",
        "report": {k: {kk: v[kk] for kk in ("old_total", "new_total", "keep_rate")}
                   for k, v in rep.items()}}
    return new, new_inputs, rep


HINT_MARK = "(Please keep your answer short"  # = tica_mw_generate.length_hint (generation only)


def needs_regen(data: dict, gens: list[dict], scores: dict[str, dict], *, thr_concept: float = 0.5,
                thr_answers: float = 0.5, len_cap_q: float | None = 0.9) -> dict[str, dict]:
    """Source texts to regenerate WITH a length hint (user 10-24: "only for the examples that are
    over long"): no eligible answer (judged + finished + <= the cap) AND at least one answer that
    was too long (over the cap, or cut at max tokens). Sources whose short answers failed the judge
    are left alone (a length hint would not help). {src_id: {concept, cap, src_len, n_over_cap,
    n_unfinished}}."""

    by_c: dict[str, list[dict]] = defaultdict(list)
    for g in gens:
        by_c[g["concept"]].append(g)
    out = {}
    for c in data["concepts"]:
        rows = by_c.get(c["concept"])
        if not rows:
            continue
        cap = length_cap([len(t["text"]) for sp in SPLITS for t in c[sp]], len_cap_q)
        per_src: dict[str, list[dict]] = defaultdict(list)
        for g in rows:
            per_src[g["src_id"]].append(g)
        for sid, gs in sorted(per_src.items()):
            ok = [g for g in gs if g["gid"] in scores
                  and keep(g, scores[g["gid"]], thr_concept, thr_answers)
                  and (cap is None or len(g["answer"]) <= cap)]
            over = sum(cap is not None and len(g["answer"]) > cap for g in gs)
            unfin = sum(not g["finished"] for g in gs)
            if not ok and (over or unfin):
                out[sid] = {"concept": c["concept"], "cap": cap, "src_len": gs[0]["src_len"],
                            "n_over_cap": over, "n_unfinished": unfin}
    return out


def verify(old: dict, new: dict, new_inputs: dict, gens: list[dict], scores: dict[str, dict], *,
           thr_concept: float = 0.5, thr_answers: float = 0.5,
           len_cap_q: float | None = 0.9) -> dict:
    """Re-check a built file from scratch: every text of a regenerated concept must be a generation
    that finished, passed the judge (concept + answer) and is <= the cap; its stored request must be
    the published one (no length-hint line). Per concept: counts, violations, lengths, judge
    scores of the KEPT texts, share written with a length hint."""

    by_tid: dict[str, list[dict]] = defaultdict(list)  # identical answers can recur (short texts)
    for g in gens:
        by_tid[text_id(g["answer"])].append(g)
    oldc = {c["concept"]: c for c in old["concepts"]}
    rep, bad_total = {}, 0
    for c in new["concepts"]:
        o = oldc[c["concept"]]
        old_ids = {t["id"] for sp in SPLITS for t in o[sp]}
        texts = [t for sp in SPLITS for t in c[sp]]
        if {t["id"] for t in texts} == old_ids:
            continue  # untouched concept
        cap = length_cap([len(t["text"]) for sp in SPLITS for t in o[sp]], len_cap_q)
        viol = Counter()
        pc, pa, hint, lens = [], [], 0, []
        for t in texts:
            cands = by_tid.get(t["id"])
            if not cands:
                viol["not_a_generation"] += 1
                continue
            req = new_inputs.get(t["id"], "")
            # the generation the build kept: same concept + request, finished, passed the judge
            g = next((g for g in cands if g["concept"] == c["concept"] and g["user"] == req
                      and g["gid"] in scores and keep(g, scores[g["gid"]], thr_concept,
                                                      thr_answers)), cands[0])
            s = scores.get(g["gid"], {})
            if not g["finished"]:
                viol["unfinished"] += 1
            if not s:
                viol["unjudged"] += 1
            elif not keep(g, s, thr_concept, thr_answers):
                viol["judge_fail"] += 1
            if cap is not None and len(t["text"]) > cap:
                viol["over_cap"] += 1
            if not req or HINT_MARK in req:
                viol["request_missing_or_hinted"] += 1
            if s.get("p_concept") is not None:
                pc.append(s["p_concept"])
            pa.append(s.get("p_answers", 0.0))
            hint += bool(g.get("length_hint"))
            lens.append(len(t["text"]))
        old_lens = [len(t["text"]) for sp in SPLITS for t in o[sp]]
        bad_total += sum(viol.values())
        rep[c["concept"]] = {
            "old": len(old_ids), "new": len(texts), "violations": dict(viol), "cap": cap,
            "median_chars_old": statistics.median(old_lens),
            "median_chars_new": statistics.median(lens) if lens else None,
            "max_chars_new": max(lens) if lens else None,
            "kept_min_p_concept": round(min(pc), 3) if pc else None,
            "kept_mean_p_concept": round(statistics.mean(pc), 3) if pc else None,
            "kept_min_p_answers": round(min(pa), 3) if pa else None,
            "kept_mean_p_answers": round(statistics.mean(pa), 3) if pa else None,
            "length_hinted": hint}
    return {"concepts": rep, "violations_total": bad_total}


def length_cap(lengths: list[int], q: float | None) -> int | None:
    """Nearest-rank q-quantile of the published lengths (None = no cap)."""

    if q is None or not lengths:
        return None
    v = sorted(lengths)
    return v[max(0, math.ceil(q * len(v)) - 1)]


def _rate(v, thr):
    v = [x for x in v if x is not None]
    return round(sum(x >= thr for x in v) / len(v), 3) if v else None


def merge_labels(data: dict, old: dict, news: list[dict]) -> dict:
    """Labels for every id of `data`: new label files win; ids not labelled anew keep the old
    labels (the labeller with --skip-labelled skipped them because the old run covered them)."""

    ids = {t["id"] for c in data["concepts"] for sp in SPLITS for t in c[sp]}
    ids |= {t["id"] for ts in data["negatives"].values() for t in ts}
    labels = {i: v for i, v in old["labels"].items() if i in ids}
    flagged = {i: v for i, v in old.get("flagged_pass1", {}).items() if i in ids}
    n_new = 0
    old_meta = old["meta"] if isinstance(old["meta"], list) else [old["meta"]]  # merged shards
    for nw in news:
        for i, v in nw["labels"].items():
            labels[i] = v
        flagged.update(nw.get("flagged_pass1", {}))
        n_new += nw["meta"]["n_texts"]
    return {"labels": labels, "flagged_pass1": flagged,
            "meta": {"merged_from": {"old": sorted({f for m in old_meta for f in m["data"]}),
                                     "new": [n["meta"].get("data") for n in news]},
                     "n_texts_new": n_new, "n_texts": len(ids),
                     "concepts": (news[0]["meta"] if news else old_meta[0]).get("concepts"),
                     "prompt": (news[0]["meta"] if news else old_meta[0]).get("prompt")}}


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--data", required=True)
    b.add_argument("--inputs", required=True)
    b.add_argument("--gens", nargs="+", required=True)
    b.add_argument("--scores", nargs="+", required=True, help="tica_free_judge.py --row-out files")
    b.add_argument("--only", nargs="*", default=None, help="regenerate only these concepts")
    b.add_argument("--thr-concept", type=float, default=0.5)
    b.add_argument("--thr-answers", type=float, default=0.5)
    b.add_argument("--no-fill", action="store_true")
    b.add_argument("--len-cap-q", type=float, default=0.9,
                   help="answers longer than this quantile of the concept's published lengths "
                        "are not eligible (user 10-21: length-constrained); <= 0 = no cap")
    b.add_argument("--seed", type=int, default=0)
    b.add_argument("--out", required=True)
    b.add_argument("--inputs-out", required=True)
    b.add_argument("--report", required=True)
    m = sub.add_parser("merge-labels")
    m.add_argument("--data", required=True)
    m.add_argument("--old", required=True)
    m.add_argument("--new", nargs="+", required=True)
    m.add_argument("--out", required=True)
    for name in ("needs-regen", "verify"):
        x = sub.add_parser(name)
        x.add_argument("--data", required=True, help="needs-regen: published; verify: built")
        x.add_argument("--gens", nargs="+", required=True)
        x.add_argument("--scores", nargs="+", required=True)
        x.add_argument("--thr-concept", type=float, default=0.5)
        x.add_argument("--thr-answers", type=float, default=0.5)
        x.add_argument("--len-cap-q", type=float, default=0.9)
        x.add_argument("--out", required=True)
        if name == "verify":
            x.add_argument("--old-data", required=True)
            x.add_argument("--inputs", required=True, help="the built file's request map")
    a = ap.parse_args()

    if a.cmd in ("needs-regen", "verify"):
        data = json.loads(Path(a.data).read_text())
        gens = read_jsonl(a.gens)
        scores = {r["gid"]: r for r in read_jsonl(a.scores) if r.get("gid")}
        kw = dict(thr_concept=a.thr_concept, thr_answers=a.thr_answers,
                  len_cap_q=a.len_cap_q if a.len_cap_q > 0 else None)
        if a.cmd == "needs-regen":
            out = needs_regen(data, gens, scores, **kw)
            Path(a.out).write_text(json.dumps(out))
            print(f"needs-regen: {len(out)} source texts", json.dumps(
                dict(Counter(v["concept"] for v in out.values()).most_common())))
            return
        out = verify(json.loads(Path(a.old_data).read_text()), data,
                     json.loads(Path(a.inputs).read_text()), gens, scores, **kw)
        Path(a.out).write_text(json.dumps(out, indent=1))
        for k, v in out["concepts"].items():
            print(f"{k[:26]:26s} {v['old']:4d} -> {v['new']:4d}  chars {v['median_chars_old']} -> "
                  f"{v['median_chars_new']} (max {v['max_chars_new']}, cap {v['cap']})  kept "
                  f"p_concept min {v['kept_min_p_concept']} mean {v['kept_mean_p_concept']}  "
                  f"p_answers min {v['kept_min_p_answers']}  hinted {v['length_hinted']}  "
                  f"violations {v['violations'] or 0}")
        print("VIOLATIONS TOTAL", out["violations_total"])
        if out["violations_total"]:
            raise SystemExit("verify failed")
        return

    if a.cmd == "merge-labels":
        data = json.loads(Path(a.data).read_text())
        out = merge_labels(data, json.loads(Path(a.old).read_text()),
                           [json.loads(Path(p).read_text()) for p in a.new])
        Path(a.out).write_text(json.dumps(out))
        print(json.dumps(out["meta"], indent=1))
        return
    data = json.loads(Path(a.data).read_text())
    inputs = json.loads(Path(a.inputs).read_text())
    scores = {r["gid"]: r for r in read_jsonl(a.scores) if r.get("gid")}
    new, new_inputs, rep = build(data, inputs, read_jsonl(a.gens), scores,
                                 thr_concept=a.thr_concept, thr_answers=a.thr_answers,
                                 fill=not a.no_fill, seed=a.seed,
                                 len_cap_q=a.len_cap_q if a.len_cap_q > 0 else None,
                                 only=set(a.only) if a.only else None)
    new["source"]["model_written"].update(data=a.data, inputs=a.inputs, gens=a.gens,
                                          scores=a.scores)
    clash = [i for i in new_inputs if i in inputs and inputs[i] != new_inputs[i]]
    if clash:
        raise SystemExit(f"{len(clash)} new ids already map to another request")
    Path(a.out).write_text(json.dumps(new))
    Path(a.inputs_out).write_text(json.dumps({**inputs, **new_inputs}))
    Path(a.report).write_text(json.dumps(rep, indent=1))
    for k, v in rep.items():
        print(f"{k[:26]:26s} gen {v['n_gen']:5d} fin {v['finished']:.2f} concept "
              f"{v['concept_rate']} answers {v['answers_rate']} keep {v['keep_rate']:.2f} "
              f"texts {v['old_total']} -> {v['new_total']} (moved req {v['requests_moved_split']}, "
              f"chars {v['median_chars_old']} -> {v['median_chars_new']}, "
              f"cap {v['len_cap_chars']}, "
              f"no eligible {v['src_no_eligible']})" + ("  BELOW 80%" if v["below_80pct"] else ""))
    low = [k for k, v in rep.items() if v["below_80pct"]]
    print("below 80% of the old count:", low or "none")


if __name__ == "__main__":
    main()
